export const dictionaries: Record<Language, Record<TranslationKey, string>> = { ru, en };

export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function makeTranslate(language: Language): Translate {
  const table = dictionaries[language] ?? ru;
  return (key, vars) => {
    const raw = table[key] ?? ru[key] ?? String(key);
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
  };
}

